import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { createHash } from 'node:crypto';
import { mkdtemp, mkdir, readdir, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { arenaDriverFixture } from './helpers/namecheap-arena-driver.mjs';
import { imageRepository } from '../db/namecheap-images.mjs';
import { exerciseImageReferences } from './helpers/namecheap-image-checks.mjs';
const require = createRequire(import.meta.url), { build } = createRequire(require.resolve('wrangler/package.json'))('esbuild');
const fixture = arenaDriverFixture(), sql = fixture.sql;
const execute = (query, values) => fixture.execute(query.replace("JSON_SEARCH(questions,'one',?,NULL,'$[*].image.id') IS NOT NULL", "EXISTS(SELECT 1 FROM json_each(questions) image_question WHERE json_extract(image_question.value,'$.image.id')=?)"), values);
const pool = { ...fixture.pool, execute };
const base = await mkdtemp(join(tmpdir(), 'quizmint-image-routes-')), directory = join(base, 'private');
await mkdir(directory, { mode: 0o700 });
globalThis.__imagePool = pool;
globalThis.__imageEnv = { QUIZMINT_RUNTIME: 'namecheap', DB: { prepare() { throw Error('D1 must not be used.'); } }, get BUCKET() { throw Error('R2 must not be used.'); } };
const previous = Object.fromEntries(['DB_NAME', 'DB_USER', 'DB_PASSWORD', 'QUIZMINT_IMAGE_DIR'].map(key => [key, process.env[key]]));
Object.assign(process.env, { DB_NAME: 'isolated_image_test', DB_USER: 'test', DB_PASSWORD: 'test-only', QUIZMINT_IMAGE_DIR: directory });
try {
  await exerciseImageReferences({ store: imageRepository({ execute }), execute });
  const plugin = { name: 'image-runtime', setup(builder) {
    builder.onResolve({ filter: /^cloudflare:workers$/ }, () => ({ path: 'env', namespace: 'fixture' }));
    builder.onResolve({ filter: /^mysql2\/promise$/ }, () => ({ path: 'mysql', namespace: 'fixture' }));
    builder.onLoad({ filter: /.*/, namespace: 'fixture' }, args => ({ contents: args.path === 'env' ? 'export const env=globalThis.__imageEnv' : 'export const createPool=()=>globalThis.__imagePool', loader: 'js' }));
  } };
  await build({ entryPoints: ['app/api/question-images/route.ts', 'app/api/question-images/[id]/route.ts', 'app/api/teacher/route.ts'], outbase: '.', outdir: '.sites-runtime/namecheap-image-routes', bundle: true, platform: 'node', format: 'esm', outExtension: { '.js': '.mjs' }, plugins: [plugin] });
  const upload = await import('../.sites-runtime/namecheap-image-routes/app/api/question-images/route.mjs');
  const image = await import('../.sites-runtime/namecheap-image-routes/app/api/question-images/[id]/route.mjs');
  const teacher = await import('../.sites-runtime/namecheap-image-routes/app/api/teacher/route.mjs');
  const root = 'https://quizmint.test', ownerToken = '1'.repeat(64), otherToken = '2'.repeat(64);
  const hash = value => createHash('sha256').update(value).digest('hex');
  for (const [id, token] of [['owner', ownerToken], ['other', otherToken]]) {
    sql.prepare('INSERT INTO creator_users VALUES(?,?,?,?,?)').run(id, id + '@example.test', 'hash', 'salt', 'now');
    sql.prepare('INSERT INTO creator_sessions VALUES(?,?,?)').run(hash(token), id, Date.now() + 600000);
  }
  const png = new Uint8Array([137,80,78,71,13,10,26,10,0,1,2]);
  const request = (path, method = 'GET', body, token = ownerToken, origin = root) => new Request(root + path, { method, headers: { Origin: origin, ...(token ? { Cookie: '__Host-quiz_session=' + token } : {}) }, ...(body ? { body } : {}) });
  assert.equal((await upload.POST(request('/api/question-images', 'POST', png, ''))).status, 401);
  assert.equal((await upload.POST(request('/api/question-images', 'POST', png, ownerToken, 'https://evil.test'))).status, 403);
  assert.equal((await upload.POST(request('/api/question-images', 'POST', new Uint8Array(600 * 1024 + 1)))).status, 400);
  assert.equal((await upload.POST(request('/api/question-images', 'POST', '<svg></svg>'))).status, 400);
  const saved = await upload.POST(request('/api/question-images', 'POST', png)); assert.equal(saved.status, 201);
  const id = (await saved.json()).id, context = { params: Promise.resolve({ id }) }, path = '/api/question-images/' + id;
  assert.match(id, /^[a-f0-9]{32}$/);
  const call = (method = 'GET', token = ownerToken, suffix = '', origin = root) => image[method](request(path + suffix, method, null, token, origin), context);
  assert.equal((await call('GET', '')).status, 404);
  assert.equal((await call('GET', otherToken)).status, 404);
  const asset = await call(); assert.equal(asset.status, 200); assert.equal(asset.headers.get('content-type'), 'image/png');
  assert.equal(asset.headers.get('cache-control'), 'private, max-age=60'); assert.equal(asset.headers.get('x-content-type-options'), 'nosniff');
  assert.deepEqual(new Uint8Array(await asset.arrayBuffer()), png);
  const question = { prompt: 'Two plus two?', options: ['1', '2', '3', '4'], correct: 3, explanation: 'Four.', image: { id, alt: 'Test image' } };
  const draft = { title: 'Image quiz', subject: 'Maths', description: 'Test', questions: [question] };
  assert.equal((await teacher.POST(request('/api/teacher', 'POST', JSON.stringify(draft), otherToken))).status, 400);
  const quizSave = await teacher.POST(request('/api/teacher', 'POST', JSON.stringify(draft))); assert.equal(quizSave.status, 201);
  const quizId = (await quizSave.json()).id;
  assert.equal((await call('GET', '', '?quiz=' + quizId)).status, 200);
  assert.equal((await call('DELETE')).status, 409);
  sql.prepare('UPDATE quizzes SET active=0 WHERE id=?').run(quizId);
  assert.equal((await call('GET', '', '?quiz=' + quizId)).status, 404);
  assert.equal((await call('DELETE')).status, 409, 'Closed saved quizzes protect images');
  const now = Date.now(), snapshot = JSON.stringify([{ ...question, image: undefined }, question]);
  sql.prepare("INSERT INTO arena_rooms(code,owner_id,title,quiz_id,questions,mode,seconds,status,question_index,deadline,remaining,version,created,expires) VALUES(?,?,?,?,?,?,?,'lobby',-1,0,0,0,?,?)").run('BCDEFG', 'owner', 'Images', quizId, snapshot, 'team', 30, now, now + 600000);
  assert.equal((await call('GET', '', '?arena=BCDEFG')).status, 404);
  sql.prepare("UPDATE arena_rooms SET status='question',question_index=0 WHERE code='BCDEFG'").run();
  assert.equal((await call('GET', '', '?arena=BCDEFG')).status, 404, 'Future question images stay private');
  sql.prepare("UPDATE arena_rooms SET question_index=1 WHERE code='BCDEFG'").run();
  assert.equal((await call('GET', '', '?arena=BCDEFG')).status, 200);
  await teacher.DELETE(request('/api/teacher?id=' + quizId, 'DELETE'));
  assert.equal((await call('DELETE')).status, 409, 'Arena snapshot protects image after source quiz deletion');
  assert.equal((await call('DELETE', otherToken)).status, 404);
  assert.equal((await call('DELETE', ownerToken, '', 'https://evil.test')).status, 403);
  sql.prepare("UPDATE arena_rooms SET expires=0 WHERE code='BCDEFG'").run();
  assert.equal((await call('GET', '', '?arena=BCDEFG')).status, 404);
  assert.equal((await call('DELETE')).status, 200); assert.equal((await call()).status, 404);
  assert.equal((await readdir(directory)).length, 0);
  console.log('Namecheap image route checks passed: private filesystem uploads, owner checks, size/type limits, quiz visibility, Arena current/future images, saved-image protection and deletion. No D1 or R2 used.');
} finally {
  for (const [key, value] of Object.entries(previous)) value === undefined ? delete process.env[key] : process.env[key] = value;
  fixture.close(); await rm(base, { recursive: true, force: true });
}
