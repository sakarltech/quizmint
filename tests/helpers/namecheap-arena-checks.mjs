import assert from 'node:assert/strict';
export async function exerciseArenaStore({ store, execute, failNextDelete }) {
  const now = Date.now();
  const questions = JSON.stringify([{ prompt: 'Two plus two?', options: ['1', '2', '3', '4'], correct: 3, explanation: 'Four.' }, { prompt: 'One plus one?', options: ['1', '2', '3', '4'], correct: 1, explanation: 'Two.' }]);
  const input = { code: 'ABCDEF', ownerId: 'owner', title: 'Arena check', quizId: 'quiz', questions, mode: 'individual', seconds: 30, now, expires: now + 86400000 };
  assert.equal(await store.create(input), true);
  assert.equal(await store.create(input), false, 'Room code collision preserves original');
  assert.equal((await store.list('owner')).length, 1);
  assert.equal((await store.list('other')).length, 0);
  assert.equal((await store.room('ABCDEF', now)).questions, questions);
  assert.equal(await store.room('MISSING', now), null);
  const join = (id, name = id) => ({ code: 'ABCDEF', id, tokenHash: id + '-hash', name, limit: 2 });
  assert.equal((await store.join(join('a', 'Alice'))).created, true);
  const reconnect = await store.join({ ...join('unused', 'Changed name'), tokenHash: 'a-hash' });
  assert.equal(reconnect.created, false); assert.equal(reconnect.player.id, 'a'); assert.equal(reconnect.player.name, 'Alice');
  assert.equal(await store.join(join('name-collision', 'ALICE')), null);
  assert.equal((await store.join(join('b', 'Bob'))).created, true);
  assert.equal(await store.join(join('c')), null, 'Room cap is enforced');
  assert.equal((await store.participant('ABCDEF', 'a-hash')).id, 'a');
  assert.equal(await store.participant('ABCDEF', 'unknown'), null);
  assert.equal(await store.remove({ code: 'ABCDEF', ownerId: 'other', version: 0, playerId: 'b' }), false);
  assert.equal(await store.remove({ code: 'ABCDEF', ownerId: 'owner', version: 1, playerId: 'b' }), false);
  assert.equal(await store.remove({ code: 'ABCDEF', ownerId: 'owner', version: 0, playerId: 'b' }), true);
  assert.equal(await store.participant('ABCDEF', 'b-hash'), null);
  assert.equal((await store.join(join('b', 'Bob'))).created, true);
  const change = (version, next, ownerId = 'owner') => store.change({ code: 'ABCDEF', ownerId, version, next });
  const playing = { status: 'question', index: 0, deadline: Date.now() + 60000, remaining: 0 };
  assert.equal(await change(0, playing, 'other'), false);
  assert.equal(await change(0, playing), true);
  assert.equal(await change(0, playing), false, 'Stale host version cannot advance');
  assert.equal(await store.remove({ code: 'ABCDEF', ownerId: 'owner', version: 1, playerId: 'b' }), false, 'Removal closes at start');
  assert.equal(await store.join(join('late')), null);
  const answer = (playerId, choice, extra = {}) => store.answer({ code: 'ABCDEF', playerId, index: 0, version: 1, choice, ...extra });
  assert.equal(await answer('intruder', 3), null);
  assert.equal(await answer('a', 4), null);
  assert.equal(await answer('a', 3, { version: 0 }), null);
  assert.equal((await answer('a', 3)).selected, 3);
  assert.equal((await answer('a', 0)).selected, 3, 'Duplicate submissions keep the original selection');
  assert.equal(await store.answerCount('ABCDEF', 0), 1);
  assert.equal((await store.leaders('ABCDEF', -1))[0].score, 0, 'Current scores stay hidden before reveal');
  assert.equal(await change(1, { status: 'paused', index: 0, deadline: 0, remaining: 15000 }), true);
  assert.equal(await answer('b', 3, { version: 2 }), null, 'Paused questions reject answers');
  assert.equal(await change(2, playing), true);
  await execute('UPDATE arena_rooms SET deadline=0 WHERE code=?', ['ABCDEF']);
  assert.equal(await answer('b', 3, { version: 3 }), null, 'Expired deadline rejects answers using database time');
  assert.equal(await change(3, { status: 'paused', index: 0, deadline: 0, remaining: 1 }), false);
  assert.equal(await change(3, { status: 'reveal', index: 0, deadline: 0, remaining: 0 }), true);
  assert.equal(await answer('b', 3, { version: 4 }), null);
  const leaders = await store.leaders('ABCDEF', 0);
  assert.equal(leaders[0].id, 'a'); assert.equal(leaders[0].score, 1000); assert.equal(leaders[0].correct, 1);
  assert.equal(leaders[1].score, 0);
  assert.equal(await store.delete('ABCDEF', 'other'), false);
  failNextDelete(); await assert.rejects(store.delete('ABCDEF', 'owner'));
  assert.equal(await store.answerCount('ABCDEF', 0), 1, 'Deletion failure restores answers');
  assert.ok(await store.participant('ABCDEF', 'a-hash'));
  assert.ok(await store.room('ABCDEF', now));
  assert.equal(await store.delete('ABCDEF', 'owner'), true);
  assert.equal(await store.room('ABCDEF', now), null);
  assert.equal(await store.participant('ABCDEF', 'a-hash'), null);
  assert.equal(await store.answerCount('ABCDEF', 0), 0);
  await store.create({ ...input, code: 'EXPIRE', expires: now - 1 });
  assert.equal(await store.room('EXPIRE', now), null);
  assert.equal(await store.join({ ...join('expired'), code: 'EXPIRE' }), null);
  assert.equal(await store.change({ code: 'EXPIRE', ownerId: 'owner', version: 0, next: playing }), false);
  assert.equal(await store.delete('EXPIRE', 'owner'), true, 'Owners can clean up expired rooms');
}
