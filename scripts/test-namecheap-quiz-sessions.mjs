import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { namecheapDatabase, closeNamecheapDatabase } from '../db/namecheap.mjs';
import { quizRepository } from '../db/namecheap-quizzes.mjs';
import { quizSessionRepository } from '../db/namecheap-quiz-sessions.mjs';
import { quizTestTables } from '../db/namecheap-quiz-test-tables.mjs';
let connection, phase = 'connection';
try {
  connection = await (await namecheapDatabase()).getConnection();
  const tables = quizTestTables(randomUUID().replaceAll('-', '').slice(0, 12));
  phase = 'temporary table creation';
  for (const statement of tables.definitions) await connection.query(statement);
  const execute = (sql, values) => connection.execute(tables.sql(sql), values);
  const pool = { execute, getConnection: async () => ({ execute, beginTransaction: () => connection.beginTransaction(), commit: () => connection.commit(), rollback: () => connection.rollback(), release() {} }) };
  const quizzes = quizRepository(pool), sessions = quizSessionRepository(pool);
  const quizId = randomUUID(), now = Date.now(), created = new Date(now).toISOString();
  const quiz = { title: 'Temporary timing check', subject: 'Maths', description: 'Temporary only', timeLimitMinutes: 1, questions: [{ prompt: '2+2?', options: ['1','2','3','4'], correct: 3, explanation: 'Four' }, { prompt: '1+1?', options: ['1','2','3','4'], correct: 1, explanation: 'Two' }] };
  await quizzes.create({ id: quizId, quiz, ownerId: 'synthetic-owner', created });
  const input = { id: randomUUID(), quizId, tokenHash: 'a'.repeat(64), student: 'synthetic@quizmint.invalid', snapshot: JSON.stringify(quiz), answers: '[-1,-1]', deadline: now + 60000, now };
  phase = 'start and resume';
  assert.equal(await sessions.start(input), true);
  assert.equal((await sessions.find(quizId, input.tokenHash)).snapshot, input.snapshot);
  assert.equal(await sessions.find(quizId, 'b'.repeat(64)), null);
  phase = 'progress and stale revision';
  await sessions.save({ id: input.id, quizId, revision: 0, answers: '[3,-1]', step: 1, now });
  await sessions.save({ id: input.id, quizId, revision: 0, answers: '[0,0]', step: 0, now });
  const saved = await sessions.find(quizId, input.tokenHash);
  assert.equal(saved.revision, 1);
  assert.equal(saved.answers, '[3,-1]');
  phase = 'finalization and duplicate result';
  const result = JSON.stringify({ score: 2, total: 2, student: input.student, created, timedOut: false });
  const finish = { id: input.id, quizId, revision: 1, result, answers: '[3,1]', now, expired: false };
  await sessions.finalize(finish);
  await sessions.finalize({ ...finish, result: JSON.stringify({ score: 0, total: 2, student: input.student, created }), answers: '[0,0]' });
  assert.equal((await sessions.find(quizId, input.tokenHash)).result, result);
  assert.equal((await quizzes.attempt(input.id, quizId)).result, result);
  assert.equal((await quizzes.attempts(quizId, 0)).length, 1);
  phase = 'database deadline enforcement';
  const expired = { ...input, id: randomUUID(), tokenHash: 'c'.repeat(64), deadline: now - 1000, answers: '[3,-1]' };
  assert.equal(await sessions.start(expired), true);
  await sessions.save({ id: expired.id, quizId, revision: 0, answers: '[3,1]', step: 1, now });
  assert.equal((await sessions.find(quizId, expired.tokenHash)).answers, '[3,-1]');
  await sessions.finalize({ ...finish, id: expired.id, revision: 0 });
  assert.equal((await sessions.find(quizId, expired.tokenHash)).result, null);
  const partial = JSON.stringify({ score: 1, total: 2, student: input.student, created, timedOut: true });
  await sessions.finalize({ ...finish, id: expired.id, revision: 0, result: partial, answers: '[3,-1]', expired: true });
  assert.equal((await quizzes.attempt(expired.id, quizId)).result, partial);
  phase = 'quiz closure';
  await quizzes.setActive(quizId, false, { id: 'synthetic-owner', isAdmin: false });
  assert.equal(await sessions.find(quizId, input.tokenHash), null);
  assert.equal(await sessions.start({ ...input, id: randomUUID(), tokenHash: 'd'.repeat(64) }), false);
  console.log('MariaDB timed quiz checks passed: resume, saved progress, stale revisions, finalization, duplicate results, deadlines and closed quizzes. Permanent application data unchanged.');
} catch (error) {
  const code = typeof error?.code === 'string' && /^[A-Z0-9_]+$/.test(error.code) ? error.code : null;
  console.error(`Timed quiz checks failed during ${phase}${code ? ` (${code})` : ''}.`);
  process.exitCode = 1;
} finally {
  if (connection) connection.destroy();
  await closeNamecheapDatabase();
}
